#!/usr/bin/env python3
"""Pasa la comparativa de memoria (web/ram.json, de tools/ram_benchmark.py) a la web.

Escribe, en web/index.html y web/en/index.html, una barra por navegador (de menos a más
memoria), con su versión, y la fecha de la medida. Las barras son SVG con su ancho como
atributo: la web no permite estilos en línea. Con --check solo comprueba que esté al día.

    python3 tools/web_ram.py            # regenera
    python3 tools/web_ram.py --check    # falla si la web no coincide con web/ram.json
"""
import argparse
import datetime
from html import escape
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'web/ram.json'
WEB = {'es': ROOT / 'web/index.html', 'en': ROOT / 'web/en/index.html'}
BEGIN, END = '<!-- @@KITSUNE_RAM_BEGIN@@ -->', '<!-- @@KITSUNE_RAM_END@@ -->'
DATE = re.compile(r'<span data-ram-date>[^<]*</span>')
MONTHS = ('enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre')


def megabytes(value, language):
    """En castellano, las cifras de cuatro dígitos van sin separador (1271) y las de cinco, con punto."""
    if language == 'en':
        return f'{value:,} MB'
    return f'{value} MB' if value < 10000 else f'{value:,} MB'.replace(',', '.')


def short_version(result):
    """«Mozilla Firefox 158.0» → «Firefox 158», «Google Chrome for Testing 155.0.8059.79» → «Chrome 155»,
    «Kitsune 0.8.0 · Gecko 157.0.1» → «Kitsune 0.8 · Gecko 157»."""
    text = result.get('version') or result['browser']
    if text.startswith('Kitsune '):
        kitsune, _, gecko = text.partition(' · Gecko ')
        number = '.'.join(kitsune.removeprefix('Kitsune ').split('.')[:2])
        return f'Kitsune {number}' + (f' · Gecko {gecko.split(".")[0]}' if gecko else '')
    words = text.replace('Mozilla ', '').replace('Google ', '').replace(' for Testing', '').split(' ')
    name, number = ' '.join(words[:-1]) or words[0], words[-1]
    if not any(character.isdigit() for character in number):
        return text
    return f'{name} {number.split(".")[0] if number.count(".") >= 3 else number.removesuffix(".0")}'


def render(report, language):
    results = sorted(report['results'], key=lambda result: result['pssMB'])
    top = max(result['pssMB'] for result in results)
    saver = 'with saver mode' if language == 'en' else 'con modo ahorro'
    items = []
    for result in results:
        kitsune = result['browser'].lower().startswith('kitsune')
        name = short_version(result) + (f' <small>{saver}</small>' if result['saver'] else '')
        width = round(100 * result['pssMB'] / top, 1)
        items.append(f'        <li{" class=\"ram-kitsune\"" if kitsune else ""}><span class="ram-name">{name}</span>'
                     f'<svg class="ram-bar" viewBox="0 0 100 8" preserveAspectRatio="none" aria-hidden="true"><rect width="100" height="8"/><rect class="ram-fill" width="{width}" height="8"/></svg>'
                     f'<b>{escape(megabytes(result["pssMB"], language))}</b></li>')
    note = 'Generated by tools/web_ram.py from web/ram.json. Do not edit.' if language == 'en' else 'Generado por tools/web_ram.py desde web/ram.json. No editar.'
    return f'{BEGIN}\n      <!-- {note} -->\n      <ol class="ram">\n' + '\n'.join(items) + f'\n      </ol>\n      {END}'


def date(report, language):
    day = datetime.date.fromisoformat(report['date'])
    text = f'{day:%B} {day.day}, {day.year}' if language == 'en' else f'{day.day} de {MONTHS[day.month - 1]} de {day.year}'
    return f'<span data-ram-date>{text}</span>'


def updated(page, report, language):
    start, stop = page.index(BEGIN), page.index(END) + len(END)
    page = page[:start] + render(report, language) + page[stop:]
    return DATE.sub(date(report, language), page)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    report = json.loads(DATA.read_text())
    stale = []
    for language, path in WEB.items():
        page = path.read_text()
        if BEGIN not in page or END not in page:
            print(f'{path.relative_to(ROOT)}: faltan las marcas de la comparativa', file=sys.stderr)
            return 1
        new = updated(page, report, language)
        if new == page:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(new)
    if stale:
        print(f'{", ".join(stale)} no está al día con web/ram.json: ejecuta tools/web_ram.py', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
