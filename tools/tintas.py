#!/usr/bin/env python3
"""Comprueba el catálogo de tintas (start/tintas.json) y lo copia al inicio integrado y a la web.

El catálogo se valida entero: forma, ids, colores y que cada tinta se lea al menos tan bien
como Papel en Claro y en Oscuro (install/tintas.py). Después se escribe, tal cual, en el
bloque generado de install/home-extension/api/core.sys.mjs, que es lo que usa el inicio de
Windows y macOS (sin servidor), y como muestras en la web (web/index.html y web/en/index.html),
con el nombre en inglés de start/en.mjs. Con --check solo comprueba que esté al día.

    python3 tools/tintas.py            # valida y regenera
    python3 tools/tintas.py --check    # falla si core.sys.mjs no coincide con el catálogo
"""
import argparse
import importlib.util
from html import escape
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / 'install/home-extension/api/core.sys.mjs'
BEGIN, END = '// @@KITSUNE_TINTAS_BEGIN@@', '// @@KITSUNE_TINTAS_END@@'
WEB = {'es': ROOT / 'web/index.html', 'en': ROOT / 'web/en/index.html'}
WEB_BEGIN, WEB_END = '<!-- @@KITSUNE_TINTAS_BEGIN@@ -->', '<!-- @@KITSUNE_TINTAS_END@@ -->'
spec = importlib.util.spec_from_file_location('kitsune_tintas', ROOT / 'install/tintas.py')
tintas = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tintas)


def render(catalog):
    body = json.dumps(list(catalog.values()), ensure_ascii=False, indent=2)
    return f"{BEGIN}\n// Generado por tools/tintas.py desde start/tintas.json. No editar.\nexport const TINTAS = Object.freeze({body})\n{END}"


def english_names():
    """Los textos de start/en.mjs ('Bambú': 'Bamboo'), para los nombres de las tintas de serie."""
    text = (ROOT / 'start/en.mjs').read_text()
    return dict(re.findall(r"^\s*'([^'\n]+)': '([^'\n]+)',?$", text, re.M))


def swatch(ink, light, dark, label):
    """Un inicio en miniatura: la mitad izquierda en Claro y la derecha en Oscuro.

    Solo atributos de SVG (la web no permite estilos en línea)."""
    def half(x, c):
        return (f'<rect x="{x}" width="100" height="120" fill="{c["bg"]}"/>'
                f'<circle cx="{x + 50}" cy="34" r="13" fill="none" stroke="{c["primary"]}" stroke-width="3.5" stroke-dasharray="70 12"/>'
                f'<rect x="{x + 14}" y="58" width="72" height="14" rx="7" fill="{c["surface"]}" stroke="{c["outline"]}"/>'
                f'<rect x="{x + 22}" y="63" width="30" height="4" rx="2" fill="{c["muted"]}"/>'
                + ''.join(f'<rect x="{x + 18 + i * 23}" y="84" width="18" height="18" rx="5" fill="{c["surfaceHigh"] if i != 1 else c["primaryContainer"]}"/>' for i in range(3)))
    return (f'<svg viewBox="0 0 200 120" role="img" aria-label="{escape(label)}">{half(0, light)}{half(100, dark)}</svg>')


def render_web(catalog, language):
    names = english_names() if language == 'en' else {}
    by = 'by' if language == 'en' else 'de'
    items = []
    for ink in catalog.values():
        name = names.get(ink['name'], ink['name'])
        label = f'{name}: light and dark' if language == 'en' else f'{name} en Claro y en Oscuro'
        items.append(f'        <li class="tinta">{swatch(ink, ink["claro"], ink["oscuro"], label)}'
                     f'<b>{escape(name)}</b> <small>{by} {escape(ink["author"])}</small></li>')
    note = 'Generated by tools/tintas.py from start/tintas.json. Do not edit.' if language == 'en' else 'Generado por tools/tintas.py desde start/tintas.json. No editar.'
    return f'{WEB_BEGIN}\n      <!-- {note} -->\n      <ul class="tintas">\n' + '\n'.join(items) + f'\n      </ul>\n      {WEB_END}'


def replace_block(text, begin, end, block):
    start, stop = text.index(begin), text.index(end) + len(end)
    return text[:start] + block + text[stop:]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        catalog = tintas.parse(json.loads((ROOT / 'start/tintas.json').read_text()))
    except ValueError as error:
        print(f'tintas.json: {error}', file=sys.stderr)
        return 1
    block, text = render(catalog), CORE.read_text()
    pages = {language: (path, render_web(catalog, language), path.read_text()) for language, path in WEB.items()}
    if args.check:
        stale = [] if block in text else ['core.sys.mjs']
        stale += [path.name if language == 'es' else f'en/{path.name}' for language, (path, web, page) in pages.items() if web not in page]
        if stale:
            print(f'{", ".join(stale)} no está al día con start/tintas.json: ejecuta tools/tintas.py', file=sys.stderr)
            return 1
        return 0
    for path, web, page in pages.values():
        if WEB_BEGIN in page:
            path.write_text(replace_block(page, WEB_BEGIN, WEB_END, web))
    if BEGIN in text:
        start, end = text.index(BEGIN), text.index(END) + len(END)
        text = text[:start] + block + text[end:]
    else:
        text = text.rstrip('\n') + '\n\n' + block + '\n'
    CORE.write_text(text)
    print(f'{len(catalog)} tintas')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
